/** One row of the zip manifest: one member, as Python's zipfile read it. */
struct ZipManifestRow {
  std::string archive;
  size_t index = 0;
  std::string name;
  uint64_t size = 0;
  uint64_t compressed_size = 0;
  uint16_t method = 0;
  uint32_t crc = 0;
  /** The six DOS fields, as `YYYY-MM-DDThh:mm:ss`. */
  std::string dos_datetime;
  uint16_t flags = 0;
  bool utf8 = false;
  /** `(external_attr >> 16) & 0xFFFF`, which is a Unix mode where there is one. */
  uint32_t mode = 0;
  /** `version made by`'s high byte: 3 is Unix. */
  unsigned create_system = 0;
  unsigned version_needed = 0;
  uint64_t header_offset = 0;
  std::string comment;
  /** The extra field's ids and lengths, as `id/len,id/len`. */
  std::string extra_ids;

  /**
   * The total length of the extra field the ids describe.
   *
   * Four bytes of header per field plus its payload. Derived here rather than
   * being a column of its own, because the ids are what the generator can report
   * without decoding a payload - and this is the one number a reader's walk over
   * the block can be checked against.
   */
  size_t extra_length() const {
    size_t total = 0;
    size_t at = 0;
    while (at < extra_ids.size()) {
      const size_t comma = extra_ids.find(',', at);
      const std::string field = extra_ids.substr(at,
          comma == std::string::npos ? std::string::npos : comma - at);
      const size_t slash = field.find('/');
      if (field.size() && field[0] == '+') {
        // A trailing fragment the generator could not parse as a field. It is
        // still part of the block's length.
        total += std::strtoul(field.c_str() + 1, nullptr, 10);
      }
      else if (slash != std::string::npos) {
        total += 4u + std::strtoul(field.c_str() + slash + 1, nullptr, 10);
      }
      if (comma == std::string::npos) {
        break;
      }
      at = comma + 1u;
    }
    return total;
  }

  /**
   * The DOS date and time as seconds since the epoch, read as UTC.
   *
   * **`timegm` on purpose, rather than the library's own conversion.** The point
   * of comparing against this is that two independent implementations of the
   * civil-date arithmetic agree; calling into the library would compare it with
   * itself. `timegm` is not in C17, which is why the library cannot use it - it
   * is in POSIX, and these tests are built for one platform where the library is
   * not.
   */
  int64_t dos_epoch() const {
    std::tm parts;
    std::memset(&parts, 0, sizeof(parts));
    unsigned year = 0, month = 0, day = 0, hour = 0, minute = 0, second = 0;
    if (std::sscanf(dos_datetime.c_str(), "%u-%u-%uT%u:%u:%u", &year, &month,
            &day, &hour, &minute, &second)
        != 6) {
      return 0;
    }
    parts.tm_year = static_cast<int>(year) - 1900;
    parts.tm_mon = static_cast<int>(month) - 1;
    parts.tm_mday = static_cast<int>(day);
    parts.tm_hour = static_cast<int>(hour);
    parts.tm_min = static_cast<int>(minute);
    parts.tm_sec = static_cast<int>(second);
    return static_cast<int64_t>(timegm(&parts));
  }
};

/** Split a tab-separated line, padding to `columns` fields. */
inline std::vector<std::string> zip_split(
    const std::string & line, size_t columns) {
  std::vector<std::string> fields;
  std::string field;
  std::istringstream split(line);
  while (std::getline(split, field, '\t')) {
    fields.push_back(field);
  }
  while (fields.size() < columns) {
    fields.push_back("");
  }
  return fields;
}

/** Every manifest row, grouped by archive and in file order. */
inline std::map<std::string, std::vector<ZipManifestRow>> zip_manifest_load(
    const std::string & path) {
  std::map<std::string, std::vector<ZipManifestRow>> rows;
  std::ifstream input(path);
  if (!input) {
    return rows;
  }
  std::string line;
  while (std::getline(input, line)) {
    if (line.empty() || line[0] == '#') {
      continue;
    }
    const std::vector<std::string> fields = zip_split(line, 16);
    ZipManifestRow row;
    row.archive = fields[0];
    row.index = std::strtoul(fields[1].c_str(), nullptr, 10);
    row.name = manifest_unescape(fields[2]);
    row.size = std::strtoull(fields[3].c_str(), nullptr, 10);
    row.compressed_size = std::strtoull(fields[4].c_str(), nullptr, 10);
    row.method = static_cast<uint16_t>(std::strtoul(fields[5].c_str(), nullptr, 10));
    row.crc = static_cast<uint32_t>(std::strtoul(fields[6].c_str(), nullptr, 16));
    row.dos_datetime = fields[7];
    row.flags = static_cast<uint16_t>(std::strtoul(fields[8].c_str(), nullptr, 16));
    row.utf8 = fields[9] == "1";
    // Octal, with the leading 0 the generator writes.
    row.mode = static_cast<uint32_t>(std::strtoul(fields[10].c_str(), nullptr, 8));
    row.create_system = std::strtoul(fields[11].c_str(), nullptr, 10);
    row.version_needed = std::strtoul(fields[12].c_str(), nullptr, 10);
    row.header_offset = std::strtoull(fields[13].c_str(), nullptr, 10);
    row.comment = manifest_unescape(fields[14]);
    row.extra_ids = fields[15];
    rows[row.archive].push_back(row);
  }
  return rows;
}

/** One row of `names.tsv`: what bsdtar decided a member is. */
struct ZipNameRow {
  std::string archive;
  size_t index = 0;
  /** "file", "directory", "symlink" or "other". */
  std::string type;
  /** libarchive's rendering of the mode, e.g. `-rw-r--r--`. */
  std::string mode;
  std::string name;
  std::string link;
};

/** Every names.tsv row, grouped by archive and in file order. */
inline std::map<std::string, std::vector<ZipNameRow>> zip_names_load(
    const std::string & path) {
  std::map<std::string, std::vector<ZipNameRow>> rows;
  std::ifstream input(path);
  if (!input) {
    return rows;
  }
  std::string line;
  while (std::getline(input, line)) {
    if (line.empty() || line[0] == '#') {
      continue;
    }
    const std::vector<std::string> fields = zip_split(line, 6);
    ZipNameRow row;
    row.archive = fields[0];
    row.index = std::strtoul(fields[1].c_str(), nullptr, 10);
    row.type = fields[2];
    row.mode = manifest_unescape(fields[3]);
    row.name = manifest_unescape(fields[4]);
    row.link = manifest_unescape(fields[5]);
    rows[row.archive].push_back(row);
  }
  return rows;
}

/** One row of `openings.tsv`: whether a reference would open an archive. */
struct ZipOpeningRow {
  std::string archive;
  std::string reference;
  /** "accepted" or "refused". */
  std::string verdict;
  /** The exit status, or "-" for the in-process reference. */
  std::string status;
  std::string note;

  bool refused() const {
    return verdict == "refused";
  }
};

/** Every openings.tsv row, in file order. */
inline std::vector<ZipOpeningRow> zip_openings_load(const std::string & path) {
  std::vector<ZipOpeningRow> rows;
  std::ifstream input(path);
  if (!input) {
    return rows;
  }
  std::string line;
  while (std::getline(input, line)) {
    if (line.empty() || line[0] == '#') {
      continue;
    }
    const std::vector<std::string> fields = zip_split(line, 5);
    ZipOpeningRow row;
    row.archive = fields[0];
    row.reference = fields[1];
    row.verdict = fields[2];
    row.status = fields[3];
    row.note = manifest_unescape(fields[4]);
    rows.push_back(row);
  }
  return rows;
}

/**
 * One row of `verdicts.tsv`: what each extractor did with one member's name.
 *
 * Every column is an *action* and not a policy, because **zip has no reference
 * that states one**: PEP 706 gave `tarfile` a `data_filter` whose verdict is a
 * documented decision and `zipfile` has no equivalent. So a Python value here may
 * be an exception name, which is the filesystem answering rather than a check
 * refusing - see verdicts() in the generator.
 */
struct ZipVerdictRow {
  std::string archive;
  size_t index = 0;
  std::string name;
  /** `same`, `rewrite=<name>`, `refused=<reason>`, an exception name, or `-`. */
  std::string python;
  std::string unzip;
  std::string libarchive;

  /** Whether a value means the reference created the member's own name. */
  static bool unchanged(const std::string & value) {
    return value == "same";
  }

  /** Whether a value means the reference did something other than accept it. */
  static bool acted(const std::string & value) {
    return value != "same" && value != "-";
  }

  /**
   * Whether a value is a refusal *about the name*.
   *
   * A `refused=` value is not always about the name: a member whose method a
   * reference does not implement is refused too, and a relation stated over names
   * has to be able to tell them apart. The reason is in the value, which is why
   * the generator keeps it.
   */
  static bool refused_for_path(const std::string & value) {
    return value.rfind("refused=", 0) == 0
        && value.find("Path contains") != std::string::npos;
  }
};

/** Every verdicts.tsv row, in file order. */
inline std::vector<ZipVerdictRow> zip_verdicts_load(const std::string & path) {
  std::vector<ZipVerdictRow> rows;
  std::ifstream input(path);
  if (!input) {
    return rows;
  }
  std::string line;
  while (std::getline(input, line)) {
    if (line.empty() || line[0] == '#') {
      continue;
    }
    const std::vector<std::string> fields = zip_split(line, 6);
    ZipVerdictRow row;
    row.archive = fields[0];
    row.index = std::strtoul(fields[1].c_str(), nullptr, 10);
    row.name = manifest_unescape(fields[2]);
    row.python = fields[3];
    row.unzip = fields[4];
    row.libarchive = fields[5];
    rows.push_back(row);
  }
  return rows;
}

/** One row of `decrypted.tsv`: an encrypted member's plaintext, from three. */
struct ZipDecryptedRow {
  std::string archive;
  size_t index = 0;
  std::string name;
  uint16_t method = 0;
  /** "zipcrypto" or "aes". */
  std::string scheme;
  uint64_t size = 0;
  /** `sha256:<hex>/<length>`, or `refused=<exception or exit status>`. */
  std::string python;
  std::string unzip;
  std::string sevenzip;
  /** The bytes, present only where all three digests agreed. */
  std::string plaintext;
  /** Whether the plaintext column holds bytes rather than `-`. */
  bool have_plaintext = false;
};

/** Every decrypted.tsv row, in file order. */
inline std::vector<ZipDecryptedRow> zip_decrypted_load(
    const std::string & path) {
  std::vector<ZipDecryptedRow> rows;
  std::ifstream input(path);
  if (!input) {
    return rows;
  }
  std::string line;
  while (std::getline(input, line)) {
    if (line.empty() || line[0] == '#') {
      continue;
    }
    const std::vector<std::string> fields = zip_split(line, 10);
    ZipDecryptedRow row;
    row.archive = fields[0];
    row.index = std::strtoul(fields[1].c_str(), nullptr, 10);
    row.name = manifest_unescape(fields[2]);
    row.method = static_cast<uint16_t>(
        std::strtoul(fields[3].c_str(), nullptr, 10));
    row.scheme = fields[4];
    row.size = std::strtoull(fields[5].c_str(), nullptr, 10);
    row.python = fields[6];
    row.unzip = fields[7];
    row.sevenzip = fields[8];
    // A literal `-` and an empty column both mean "no bytes here". They are not
    // the same thing to a reader of the file and they are the same thing to a
    // test, so both are folded into the flag rather than compared against.
    row.have_plaintext = fields[9] != "-" && !fields[9].empty();
    if (row.have_plaintext) {
      row.plaintext = manifest_unescape(fields[9]);
    }
    rows.push_back(row);
  }
  return rows;
}

