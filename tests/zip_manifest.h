/**
 * @file
 *
 * Reading `tests/data/zip/`: what the references say each fixture contains, and
 * what they do when handed one.
 *
 * Five files, because there are five kinds of answer and no one reference gives
 * all of them. `manifest.tsv` is Python's `zipfile` reading every field it
 * reports; `names.tsv` is bsdtar's type, mode and link target, which are
 * *decisions* Python's module does not make; `openings.tsv` is whether each of
 * four references would open the archive at all, which is where the corpus
 * records the fixtures they disagree about; `verdicts.tsv` is what three
 * extractors *do* with each member's name, which is a decision rather than a
 * reading; and `decrypted.tsv` is the plaintext of every encrypted member, from
 * three programs that decrypt it.
 *
 * All of it is generated by `tools/oracle/make_zip_corpus.py` inside the pinned
 * container. **It is the references' opinions, not this library's**, which is the
 * only reason a test comparing against it means anything.
 *
 * Copyright 2026 by Corey Pennycuff
 */

